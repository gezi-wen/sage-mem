/**
 * sage-mem 记忆层 —— 意图识别：这句话是不是在问自己的历史（纯函数，无 I/O）。
 *
 * 为什么不做分类器、为什么必须保守：判错的两个方向代价不对称。
 *   漏判（该提示没提示）只是少花一点上下文，模型自己多读一次文件；
 *   误判（不该抑制却抑制了重复正文、不该插话却插了一句）会让模型答错，
 *   或者让这句提示本身被当成噪音彻底忽略。所以只在**明确**时才出声。
 *
 * 为什么不用问号当判据：「今天天气怎么样？」与「上次为什么这么定？」都带问号，
 * 它区分不了任何东西；反过来，没有问号也完全可能是提问。任何以标点为信号的
 * 规则都会在真实语料里翻车，所以这里一条都没有。
 *
 * 可解释性来源：`INTENT_RULES` **就是实现本身**。`detectIntent` 按数组顺序逐条试，
 * 第一个命中的规则决定结果、并把命中的片段原文回报出来。规则表不是给文档看的副本 ——
 * 改表就是改行为，不存在「表里写了一套、代码里另一套」的可能。
 */

/** 意图枚举。对外字段，必须稳定。 */
export const INTENTS = Object.freeze([
  'explicit_recall',  // 显式要求回看依据：「上次」「之前」「当时」「沿用」「依据」
  'correction',       // 更正：「不是…了」「改成」「不再」
  'explain_prior',    // 问历史决定的理由：「为什么当时」「当初为什么选」
  'continue',         // 续接：「继续」「接着」「然后呢」
  'none',
])

/** 「这几类绝不能抑制重复正文」——核实、更正、问依据，用户就是要看原文。 */
export const NO_SUPPRESS_INTENTS = Object.freeze(['explicit_recall', 'correction', 'explain_prior'])

/** 「这几类算历史依赖」——够格触发正文补检索与缺口提示。 */
export const HISTORY_INTENTS = Object.freeze(['explicit_recall', 'correction', 'explain_prior', 'continue'])

/**
 * 可读的规则表（面板 / 文档要展示「凭什么这么判」）。
 *
 * **数组顺序就是优先级**：correction > explain_prior > explicit_recall > continue。
 * 一句话里同时出现多个信号时（「上次那个不是改成两格了吗」），更正与问依据比
 * 单纯「回看」更具体，所以排在前面。`none` 不是一条规则，而是「一条都没命中」。
 *
 * 写规则的约束：
 *   1. 正则**不带 `g`**（带 g 的 test() 会记住 lastIndex，同一份规则跨调用行为漂移）。
 *   2. 单个虚词不作为判据 ——「为什么」「之前」各自单独出现都不够，必须同现
 *      （否则「为什么天空是蓝的」会被当成在问历史）。
 *   3. 匹配区间一律用 `[^。！？\n]{0,n}` 限宽，避免在长文本上回溯爆炸。
 */
export const INTENT_RULES = Object.freeze([
  {
    intent: 'correction',
    patterns: Object.freeze([
      // 「改成 / 改为 / 改掉 / 改了」：明确的变更动作。单独一个「改」不算 ——
      //「这段代码怎么改」是求改法，不是宣告旧结论失效。
      /改(?:成|为|掉|了)/,
      // 「不再…了 / 不用…了 / 不要…了」：宣告旧做法失效。中间**必须真有一个对象**
      //（「不用了，谢谢」只是客套，没有对象），并排除「不用这么客气吧」这类纯礼貌搭配 ——
      // 否则一句客套就会让无关轮次也去翻正文。
      /不(?:再|用|要|选|走|做)\s*(?!\s*(?:这么|那么)?(?:客气|麻烦|担心|着急|急|慌|谢))[^，。！？；\s][^，。！？；]{0,12}(?:了|吧)/,
      // 「不是…了」：状态变了。**排除后面紧跟「吗/嘛/呢」的**——那是反问式核实
      //（「不是已经定了吗」），它既不是更正的宣告、也不足以单独证明在问历史；
      // 没有别的信号时就该落 none，宁可漏判也不要把反问判成更正。
      /不是[^，。！？；\n]{0,16}了(?![吗嘛呢])/,
      // 「换成 / 替换成」：同义改写，中文里与「改成」交替使用。
      /(?:换|替换|替代)(?:成|为|掉|了)/,
      // 用户自报更正：旧结论当场作废，是最强的一类信号。
      /更正|纠正|订正|勘误|说错了|记错了|搞错了|弄错了|写错了|我改主意/,
    ]),
    note: '更正优先于其它：用户可能同时说「上次说的那个，不是…了」——此时旧结论已作废，按回看处理会让模型引用错的那份。',
  },
  {
    intent: 'explain_prior',
    patterns: Object.freeze([
      // 「为什么 / 为啥 / 为何」+ 过去时点，**必须同现**。只靠「为什么」会把
      //「为什么天空是蓝的」这类纯知识问题全拉进来。
      /为(?:什么|啥|何)[^。！？\n]{0,24}(?:当时|当初|之前|先前|上次|上一次|原来|早先|那会儿)/,
      /(?:当时|当初|之前|先前|上次|上一次|原来|早先|那会儿)[^。！？\n]{0,24}为(?:什么|啥|何)/,
      // 「当时…的依据 / 理由 / 原因是什么」：问的是**过去那个决定凭什么**，
      // 同属 explain_prior，前面那条只认「为什么」会漏掉这种更书的问法。
      /(?:当时|当初|之前|先前|上次)[^。！？\n]{0,24}(?:理由|依据|原因|考虑|思路|出发点)[^。！？\n]{0,8}(?:是|有)?(?:什么|啥|哪)/,
    ]),
    note: '问依据/理由要排在纯回看之前：用户不只想看到原文，还想知道当时为什么这么决定，正文补检索的目标段落不同。',
  },
  {
    intent: 'explicit_recall',
    patterns: Object.freeze([
      // 过去时点：用户主动把话题锚回历史。最直接的一类信号。
      /上次|上回|上一次|之前|先前|以前|当时|当初|早先|那会儿/,
      // 「沿用 / 照旧 / 按原来」：明确要求把旧结论继续用下去。
      /沿用|照旧|按原(?:来|先)|按之前|按照之前|还是按/,
      // 「依据 / 出处」：要求给出根据 → 用户要看原文，不能拿摘要糊弄。
      /依据|出处|根据是(?:什么|啥)|哪来的(?:结论|说法|数字)/,
      // 「还记得 / 记得吗 / 回忆 / 翻记录」：明说要回看。
      /还记得|记得(?:吗|么)|回忆一下|回想一下|翻(?:一下)?(?:记忆|记录|历史)|查(?:一下)?(?:记忆|记录|历史)/,
      // 「说好的 / 约定过的」：把过去的约定当判据。
      /说好(?:的|了)|约定(?:过|好)(?:的)?|定好(?:的|了)|商量(?:过|好)(?:的)?/,
    ]),
    note: '显式回看是「用户要核实」的信号，绝不能抑制重复正文：他要看的就是原文。',
  },
  {
    intent: 'continue',
    patterns: Object.freeze([
      // 单独的「继续 / 接着 / 往下」是典型续接指令。要求它**在句首或句尾**，
      // 是为了放过「在继续讨论前，先解释一下依赖注入」这种夹在中间的用法。
      /^继续|(?:继续|接着|往下)(?:吧|啊|呀|哦|呢)?$/,
      // 「然后呢 / 然后干什么」：追问下一步。
      /然后呢|然后呐|然后(?:怎么办|做什么|做啥|干啥)/,
      // 「接下来 / 下一步」。
      /接下来(?:呢|做什么|做啥|怎么办|干(?:什么|啥))|下一步(?:呢|做什么|做啥|怎么办)/,
      // 「接着 + 动作」：「接着来 / 接着说」。要求后面真跟动作，
      // 避免「接着这个问题」被误判成续接。
      /^接着(?:来|做|说|写|改|跑|干|搞|讲|看|读)/,
      // 英文口令。整句是英文续接指令时同样成立。
      /^(?:go on|continue|keep going|resume)$/i,
    ]),
    note: '续接是最弱的一类历史依赖：它没说要回看什么，只是把话头交回上一步，所以排在最后、且只在句首句尾这种明确位置成立。',
  },
])

/** 单次判定最多回报几条命中片段 —— matched 是给人看的解释，不是全量日志。 */
const MAX_MATCHED = 8

/**
 * 只扫描前 N 个字符。
 *
 * 超长输入通常是粘贴进来的文档或代码，不是一句对话。按保守方向，宁可在长文里
 * 漏判，也不要因为正文里恰好出现「上次」「之前」就把整段粘贴当成历史追问。
 * 这个上限同时把最坏情况的计算量钉住。
 */
const SCAN_LIMIT = 4000

/**
 * 判定用户这句话的意图。
 *
 * @param {string} query
 * @returns {{intent: string, matched: string[], historyDependent: boolean, suppressible: boolean}}
 *   matched 是**命中的规则片段原文**（可解释性的来源，别只返回一个枚举）。
 */
export function detectIntent(query) {
  // 非字符串一律按 none 处理，不做隐式 toString：把一个对象或数字「猜」成话，
  // 只会让误判有机会溜进来；空串同理（没有任何信号）。
  const text = typeof query === 'string' ? query.slice(0, SCAN_LIMIT) : ''
  if (!text.trim()) return outcome('none', [])
  for (const rule of INTENT_RULES) {
    const matched = matchPatterns(text, rule.patterns)
    if (matched.length) return outcome(rule.intent, matched)
  }
  return outcome('none', [])
}

/**
 * 逐条正则收集命中的**原文片段**（去重，上限 MAX_MATCHED）。
 *
 * 为什么克隆一份带 `g` 的副本：规则表里的正则刻意不带 g，这样表可以被任何人
 * 反复 test() 而不受 lastIndex 影响；而这里要拿到全部片段原文，需要 g。
 */
function matchPatterns(text, patterns) {
  const found = []
  for (const re of patterns) {
    const flags = re.flags.replace(/[gy]/g, '') + 'g'
    for (const m of text.matchAll(new RegExp(re.source, flags))) {
      if (!m[0]) continue
      if (!found.includes(m[0])) found.push(m[0])
      if (found.length >= MAX_MATCHED) return found
    }
  }
  return found
}

/** 组装返回值。suppressible / historyDependent 都从常量推导，避免两处各写一份。 */
function outcome(intent, matched) {
  return {
    intent,
    matched,
    historyDependent: HISTORY_INTENTS.includes(intent),
    suppressible: !NO_SUPPRESS_INTENTS.includes(intent),
  }
}
