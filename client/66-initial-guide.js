		// ── 初始记忆：给 agent 的一份「建骨架」提示词（2.12.0）──────────────
		//
		// 为什么是**提示词**而不是插件替用户建文件（这是 2.12.0 唯一的设计取舍）：
		//   1. 写盘会把「覆盖用户已有记忆」变成一个必须防的风险 —— 防它要状态文件、要
		//      revision 守卫、要撤销栈，三样都是为「一个本不该有的写动作」付的保险费；
		//   2. 随包技能 `skills/sage-mem/SKILL.md` 已经把机制讲过了（frontmatter、四类
		//      前缀、检索与注入）。再来一份「初始记忆」正文，同一件事就有两份真相，
		//      然后开始漂 —— 这正是仓库里 duplication-test 在防的那类坏法；
		//   3. 「该建哪几条、用哪种语言、按谁的情况写」只有会话里的 agent 知道（它看得见
		//      用户、看得见现有库），插件在宿主里只看得见文件名。
		// 所以插件只负责一件事：给一份**可执行的清单**，复制走、粘给 agent。
		//
		// 单一真相源：正文只在本文件定义一次。卡片（`67-initial-guide-card.js`）只渲染与
		// 复制，不写自己的说法；测试直接对 `buildInitialGuide()` 的字符串断言。
		// 正文**只出中文**（与 `56-health-prompt.js`、`skills/sage-mem/SKILL.md` 同一口径），
		// 界面上的按钮与提示走 i18n（`guide.*`）。

		/** 下载时用的文件名（卡片与测试共用一份，别在别处再拼一遍）。 */
		const INITIAL_GUIDE_FILE = "sage-mem-initial-memory.md";

		/**
		 * 提示词的正文行。
		 *
		 * ⚠️ 这里**不许**出现机制细节（frontmatter 字段表、检索打分、注入预算）——
		 * 那些住随包技能里，写在这儿就是第二份真相。这里只写「这次要做什么、怎么不踩坑」。
		 */
		function initialGuideLines() {
			return [
				"请帮我给这个 sage-mem 记忆库起一个骨架。这份清单只说「这次要做什么」；机制（frontmatter 字段、四类前缀、检索与注入）在随包技能里，下面不复述。",
				"",
				"════ 第 0 步 · 先看，别先写 ════",
				"1. 先读 sage-mem 技能（随包技能 skills/sage-mem/SKILL.md），确认 frontmatter 与四类前缀的写法。",
				"2. 先列出记忆目录里现在有什么（search_memory 或直接看目录）—— 这一步的结果决定后面每一步是「新建」还是「只补一行」。",
				"3. 已有文件一律只做增量：`MEMORY.md`、`session-log.md`、以及任何和我打算新建的文件同名或同 `name:` 的，先读全文，只在缺的地方补；不要覆盖、不要重排、不要顺手「整理一下」。拿不准就停下来问我。",
				"4. 不要为了凑齐清单而建文件：某一条我库里已经有相近内容，就跟我说「已有 X，跳过」，别再写一份。",
				"",
				"════ 第 1 步 · 索引 MEMORY.md ════",
				"文件开头一行写清这个库是什么；正文按四类分区，每类一个 `##` 小标题：用户（user_）、反馈与工作方式（feedback_）、项目与进行中的事（project_）、参考资料（reference_）。",
				"每类下面一行一条：`- [文件名](文件名) — 一句话它说什么`。",
				"索引里只留仍然有效的条目，归档的不进索引。",
				"以后每次新建 / 换类型 / 归档，都要同步这一行 —— 索引和目录对不上，检索就会漏（体检会报「漏索引 / 索引悬空」）。",
				"",
				"════ 第 2 步 · 流水 session-log.md ════",
				"开头一句说明用途（这是流水，不参与检索，也不算长期结论）。每条格式固定：",
				"  ## YYYY-MM-DD HH:MM · 一句话标题",
				"  - 做了什么",
				"  - 决定了什么（以及为什么这么定）",
				"  - 留了什么尾巴",
				"每场会话收尾追加一条；长期结论不要塞进流水，写进四类记忆。",
				"",
				"════ 第 2.5 步 · 三件别做的事 ════",
				"1. 别把一整场对话原样搬进记忆 —— 那是流水的事，不是记忆的事。",
				"2. 别为了「看起来完整」补一条以后没人会读的文件；宁可库里少一条。",
				"3. 别改我的既有写法：库里已经有格式（标题层级、字段顺序、语言）就跟随它，不要另立一套。",
				"",
				"════ 第 3 步 · 三条起步记忆 ════",
				"用 write（有 write_memory 就用它，没有就直接编辑文件）新建，正文按我的实际情况写，每条约 20–40 行。frontmatter 至少 name / description / metadata。",
				"不要预置我的个人信息，不要写版本号，不要写 `baseline: true`（那会让它每场都无条件注入）。",
				"",
				"1. feedback_memory-discipline.md —— 这个库记什么、不记什么。",
				"   必须写清：靠读代码 / git / 现有文档能推出来的不存；存的是推不出来的上下文（为什么这么定、踩过什么坑、我偏好什么）。四类前缀怎么选。什么时候该归档而不是继续加长。",
				"2. reference_memory-layout.md —— 库的结构。",
				"   必须写清：记忆目录在哪、archive/ 放什么、索引与流水各自的作用、可以用哪些工具读写（有 write_memory / search_memory 就写它们，没有就写「直接编辑文件」）。",
				"3. feedback_session-hygiene.md —— 会话收尾的固定动作。",
				"   必须写清：写流水；如果启用了待办清单看板，把「已完成，待删除」里的条目搬进流水再从清单删掉；没做完的事留在清单里，别当成结论写进流水。",
				"",
				"════ 第 4 步 · 收尾 ════",
				"1. 列出新建 / 修改了哪些文件，一条一行。",
				"2. 每条新建的记忆补一句：它为什么是「推不出来的」。",
				"3. 告诉我以后每场会话收尾要做什么（三行以内）。",
				"4. 有没做或不确定的，直说 —— 不要静悄悄略过。",
			];
		}

		/**
		 * 组装后的提示词（**全库唯一入口**：卡片复制 / 下载都走它）。
		 *
		 * @returns {{text: string, file: string, lines: number}}
		 */
		function buildInitialGuide() {
			const lines = initialGuideLines();
			return { text: lines.join("\n"), file: INITIAL_GUIDE_FILE, lines: lines.length };
		}
